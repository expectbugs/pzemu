#!/usr/bin/env python3
"""Generate GAMES.md from the PZEMU loot tables.

Parses mod/PZEMU/42/media/lua/server/Items/PZEMU_Distributions.lua (the
*_GAME_POOL tables), cross-checks the named-cartridge ROM table in
mod/PZEMU/42/media/lua/client/PZEMU/PZEMUMain.lua and the DisplayNames in
mod/PZEMU/42/media/scripts/pzemu_items.txt, and writes GAMES.md at the repo root.

Standard library only. Run from anywhere:
    python3 tools/gen_games_md.py            # writes GAMES.md
    python3 tools/gen_games_md.py --check    # exit 1 if GAMES.md is out of date
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, "mod", "PZEMU", "42", "media", "lua", "server", "Items", "PZEMU_Distributions.lua")
MAIN = os.path.join(ROOT, "mod", "PZEMU", "42", "media", "lua", "client", "PZEMU", "PZEMUMain.lua")
ITEMS = os.path.join(ROOT, "mod", "PZEMU", "42", "media", "scripts", "pzemu_items.txt")
OUT = os.path.join(ROOT, "GAMES.md")

# pool variable -> (section title, rom dir, extensions, generic item, console item)
SYSTEMS = [
    ("NES_GAME_POOL",       "NES (Nintendo Entertainment System)", "nes",       ".nes",                     "PZEMU.NES_Cart_Generic",     "PZEMU.NES_Console"),
    ("SNES_GAME_POOL",      "SNES (Super Nintendo)",               "snes",      ".smc / .sfc",              "PZEMU.SNES_Cart_Generic",    "PZEMU.SNES_Console"),
    ("GENESIS_GAME_POOL",   "Sega Genesis",                        "genesis",   ".md / .gen / .bin / .smd", "PZEMU.Genesis_Cart_Generic", "PZEMU.Genesis_Console"),
    ("GB_GAME_POOL",        "Game Boy (handheld)",                 "gb",        ".gb",                      "PZEMU.GB_Cart_Generic",      "PZEMU.GameBoy_Console"),
    ("ATARI2600_GAME_POOL", "Atari 2600",                          "atari2600", ".a26 / .bin",              "PZEMU.Atari_Cart_Generic",   "PZEMU.Atari2600_Console"),
    ("GG_GAME_POOL",        "Sega Game Gear (handheld)",           "gg",        ".gg",                      "PZEMU.GG_Cart_Generic",      "PZEMU.GameGear_Console"),
    ("SMS_GAME_POOL",       "Sega Master System",                  "sms",       ".sms",                     "PZEMU.SMS_Cart_Generic",     "PZEMU.SMS_Console"),
]

BUNDLED = {"Chase.nes", "Lan_Master.nes", "Zooming_Secretary.nes"}

ENTRY_RE = re.compile(
    r'\{\s*name\s*=\s*"((?:[^"\\]|\\.)*)"\s*,\s*romFile\s*=\s*"([^"]+)"\s*,\s*'
    r'namedItem\s*=\s*(nil|"([^"]+)")\s*,\s*weight\s*=\s*([0-9.]+)\s*\}'
)


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def parse_pools(src):
    pools = {}
    for m in re.finditer(r'local\s+(\w+_GAME_POOL)\s*=\s*\{', src):
        name = m.group(1)
        # find the matching closing brace of this table (pools contain only flat {...} entries)
        depth, i = 0, m.end() - 1
        while i < len(src):
            c = src[i]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        body = src[m.end():i]
        entries = []
        for e in ENTRY_RE.finditer(body):
            entries.append({
                "name": e.group(1).replace('\\"', '"'),
                "romFile": e.group(2),
                "namedItem": e.group(4),
                "weight": float(e.group(5)),
            })
        pools[name] = entries
    return pools


def parse_named_roms(src):
    out = {}
    for m in re.finditer(r'\["(PZEMU\.[A-Za-z0-9_]+)"\]\s*=\s*"([^"]+)"', src):
        out[m.group(1)] = m.group(2)
    return out


def parse_display_names(src):
    out = {}
    cur = None
    for line in src.splitlines():
        m = re.match(r'\s*item\s+(\w+)', line)
        if m:
            cur = "PZEMU." + m.group(1)
            continue
        m = re.match(r'\s*DisplayName\s*=\s*(.+?),\s*$', line)
        if m and cur:
            out[cur] = m.group(1).strip()
    return out


def fmt_weight(w):
    return str(int(w)) if w == int(w) else ("%g" % w)


def build(pools, named_roms, display_names):
    lines = []
    lines.append("# PZEMU — Games and cartridges")
    lines.append("")
    lines.append("<!-- GENERATED by tools/gen_games_md.py from PZEMU_Distributions.lua. Do not edit by hand. -->")
    lines.append("")
    lines.append("PZEMU ships **no commercial ROMs**. Every game below is a *cartridge item* that can spawn in")
    lines.append("loot; to actually play it you must supply your own legally obtained ROM dump and drop it in")
    lines.append("the matching folder under `Zomboid/PZEMU/roms/` (see the last section). The three bundled")
    lines.append("free homebrew NES games are marked **bundled** and work out of the box.")
    lines.append("")
    lines.append("Columns: **ROM file** is the name PZEMU looks for first (exact), then it falls back to fuzzy")
    lines.append("matching. **Item** says whether the game has its own cartridge item with a dedicated icon,")
    lines.append("or spawns as the system's generic cartridge with the game name written on it.")
    lines.append("**Weight** is the relative spawn weight inside that system's pool (higher = more common);")
    lines.append("**Share** is weight / pool total. The first entry of every pool is the *must-have* game")
    lines.append("that always spawns next to a console (unless the Cartridge Count Multiplier is 0).")
    lines.append("")
    lines.append("## Contents")
    lines.append("")
    for var, title, romdir, _, _, _ in SYSTEMS:
        n = len(pools.get(var, []))
        anchor = re.sub(r"[^a-z0-9 ]", "", title.lower()).replace(" ", "-")
        lines.append(f"- [{title}](#{anchor}) — {n} games, folder `roms/{romdir}/`")
    lines.append("- [How to add your own games and cartridges](#how-to-add-your-own-games-and-cartridges)")
    lines.append("")

    total_games = 0
    for var, title, romdir, exts, generic_item, console_item in SYSTEMS:
        entries = pools.get(var, [])
        total_games += len(entries)
        pool_total = sum(e["weight"] for e in entries) or 1.0
        lines.append(f"## {title}")
        lines.append("")
        lines.append(f"Console item: `{console_item}` · generic cartridge: `{generic_item}` · ROM folder: `Zomboid/PZEMU/roms/{romdir}/` · extensions: {exts}")
        lines.append("")
        lines.append("| # | Game | ROM file | Item | Weight | Share |")
        lines.append("|---|------|----------|------|-------:|------:|")
        for i, e in enumerate(entries, 1):
            if e["namedItem"]:
                item = f"dedicated `{e['namedItem'].split('.', 1)[1]}`"
                rom_in_main = named_roms.get(e["namedItem"])
                if rom_in_main and rom_in_main != e["romFile"]:
                    item += f" ⚠ PZEMUMain expects `{rom_in_main}`"
                dn = display_names.get(e["namedItem"])
                if dn:
                    item += f" (\"{dn}\")"
            else:
                item = "generic"
            name = e["name"]
            if e["romFile"] in BUNDLED:
                name += " **(bundled)**"
            share = 100.0 * e["weight"] / pool_total
            lines.append(f"| {i} | {name} | `{e['romFile']}` | {item} | {fmt_weight(e['weight'])} | {share:.1f}% |")
        lines.append("")

    lines.append(f"**Total: {total_games} games across {len(SYSTEMS)} systems.**")
    lines.append("")
    lines.append("## How to add your own games and cartridges")
    lines.append("")
    lines.append("### 1. Where ROMs go")
    lines.append("")
    lines.append("`<Zomboid user folder>/PZEMU/roms/<system>/` where `<system>` is one of "
                 "`nes`, `snes`, `genesis`, `gb`, `atari2600`, `gg`, `sms`.")
    lines.append("")
    lines.append("- Linux: `~/Zomboid/PZEMU/roms/nes/`")
    lines.append("- Windows: `C:\\Users\\<you>\\Zomboid\\PZEMU\\roms\\nes\\`")
    lines.append("")
    lines.append("The folders are created the first time the emulator runs; you can also create them yourself.")
    lines.append("Only the extensions listed per system above are considered. Zipped ROMs are not read.")
    lines.append("")
    lines.append("### 2. How ROM names are matched")
    lines.append("")
    lines.append("When you pick a game, PZEMU looks for the exact **ROM file** name first. If it is not there,")
    lines.append("every file in the system folder (with a matching extension) is normalised and compared:")
    lines.append("")
    lines.append("1. the extension is removed;")
    lines.append("2. everything from the first `(` or `[` onwards is dropped — region, revision and dump tags")
    lines.append("   such as `(USA)`, `(Rev A)`, `(PRG1)`, `[!]`;")
    lines.append("3. apostrophes (straight and curly), commas and periods are removed;")
    lines.append("4. hyphens, en/em dashes and colons become `_`; runs of spaces/underscores collapse to one `_`;")
    lines.append("5. the result is lower-cased and common accents are stripped (Pokémon → pokemon);")
    lines.append("6. a leading `The`/`A`/`An` and a trailing `, The`/`, A`/`, An` are dropped;")
    lines.append("7. roman numerals II–X become 2–10 (`Final Fantasy III` → `final_fantasy_3`).")
    lines.append("")
    lines.append("The two normalised names must then be **identical** (there is no prefix or similarity matching,")
    lines.append("so `Dragon Warrior` never matches `Dragon Warrior II`). Examples that all resolve to")
    lines.append("`Super_Mario_Bros_3.nes`: `Super Mario Bros. 3 (USA) (PRG1) [!].nes`, `super-mario-bros-iii.nes`,")
    lines.append("`Super_Mario_Bros_3.NES`.")
    lines.append("")
    lines.append("If a game cannot be found, the emulator window shows the expected file name and the folder.")
    lines.append("")
    lines.append("### 3. Adding a game to a loot pool")
    lines.append("")
    lines.append("Open `mod/PZEMU/42/media/lua/server/Items/PZEMU_Distributions.lua` and add one line to the")
    lines.append("system's `*_GAME_POOL` table (anywhere after the first entry — the first entry is the must-have game):")
    lines.append("")
    lines.append("```lua")
    lines.append('    { name = "Bubble Bobble 2",  romFile = "Bubble_Bobble_2.nes",  namedItem = nil,  weight = 5 },')
    lines.append("```")
    lines.append("")
    lines.append("- `name` — what the cartridge is called in the inventory (the system prefix `NES: ` is added")
    lines.append("  automatically) and in the game picker.")
    lines.append("- `romFile` — the file name PZEMU expects in `roms/<system>/` (use `_` instead of spaces; the")
    lines.append("  fuzzy matcher handles most other spellings).")
    lines.append("- `namedItem = nil` — spawn as the generic cartridge of that system with the name stamped on it.")
    lines.append("- `weight` — relative spawn weight within the pool; 50 is \"everyone had this\", 1–3 is rare.")
    lines.append("")
    lines.append("Cartridges only spawn next to a console of the same system (3–7 per console, 15% chance of a")
    lines.append("bigger stash, scaled by the *Cartridge Count Multiplier* sandbox option). Changes to the pool apply")
    lines.append("to containers that have not been opened yet; already-generated loot is unaffected. Spawning is")
    lines.append("server-side: in multiplayer the server's copy of the file is what counts.")
    lines.append("")
    lines.append("### 4. Giving a game its own cartridge item (icon)")
    lines.append("")
    lines.append("Three edits:")
    lines.append("")
    lines.append("1. `mod/PZEMU/42/media/scripts/pzemu_items.txt` — add an item in module `PZEMU`:")
    lines.append("")
    lines.append("```")
    lines.append("    item NES_Cart_BubbleBobble2")
    lines.append("    {")
    lines.append("        ItemType            = base:normal,")
    lines.append("        DisplayName         = NES: Bubble Bobble 2,")
    lines.append("        Weight              = 0.1,")
    lines.append("        Icon                = PZEMU_NES_Cart_BubbleBobble2,")
    lines.append("        DisplayCategory     = Electronics,")
    lines.append("        Tags                = PZEMU_Cartridge;PZEMU_NES,")
    lines.append("        WorldStaticModel    = PZEMU_NES_Cart_Generic,")
    lines.append("    }")
    lines.append("```")
    lines.append("")
    lines.append("   and put a 32×32 (or larger, square) PNG at `mod/PZEMU/42/media/textures/Item_PZEMU_NES_Cart_BubbleBobble2.png`.")
    lines.append("2. `PZEMU_Distributions.lua` — set `namedItem = \"PZEMU.NES_Cart_BubbleBobble2\"` on the pool entry.")
    lines.append("3. `mod/PZEMU/42/media/lua/client/PZEMU/PZEMUMain.lua` — add the item to both lookup tables:")
    lines.append("   `CART_TYPE_TO_SYSTEM[\"PZEMU.NES_Cart_BubbleBobble2\"] = \"nes\"` and")
    lines.append("   `NAMED_CART_ROMS[\"PZEMU.NES_Cart_BubbleBobble2\"] = \"Bubble_Bobble_2.nes\"`.")
    lines.append("")
    lines.append("Re-run `python3 tools/gen_games_md.py` afterwards to refresh this file; it warns (⚠) when the")
    lines.append("ROM file in `PZEMUMain.lua` disagrees with the pool.")
    lines.append("")
    lines.append("### 5. Adding a whole new system")
    lines.append("")
    lines.append("Not supported by drop-in configuration: a new system needs a libretro core shipped as `.dat`,")
    lines.append("a `CONSOLES` entry in `PZEMUGame.lua` (resolution, core file, button list, key map), console and")
    lines.append("cartridge items, lookup tables in `PZEMUMain.lua` and a pool here. See `analog.md` in the repo")
    lines.append("for the advanced-user walkthrough that adds PSX/PSP cores.")
    lines.append("")
    return "\n".join(lines) + "\n"


def main(argv):
    pools = parse_pools(read(DIST))
    missing = [v for v, *_ in SYSTEMS if v not in pools]
    if missing:
        sys.exit("pool tables not found in %s: %s" % (DIST, ", ".join(missing)))
    named_roms = parse_named_roms(read(MAIN))
    display_names = parse_display_names(read(ITEMS))
    text = build(pools, named_roms, display_names)
    if "--check" in argv:
        current = read(OUT) if os.path.exists(OUT) else ""
        if current != text:
            print("GAMES.md is out of date — run tools/gen_games_md.py")
            return 1
        print("GAMES.md is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    total = sum(len(v) for v in pools.values())
    print("wrote %s (%d games, %d systems)" % (OUT, total, len(SYSTEMS)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
